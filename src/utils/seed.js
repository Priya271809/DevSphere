async function seed() {
  try {
    await connectDB();
    console.log("Connected to MongoDB for seeding...");

    const defaultPasswordHash = await bcrypt.hash("Password@123", 10);

    for (const dev of DUMMY_DEVELOPERS) {
      const existing = await User.findOne({ emailId: dev.emailId });
      if (!existing) {
        await User.create({
          ...dev,
          password: defaultPasswordHash,
        });
        console.log(`+ Seeded developer: ${dev.firstName} ${dev.lastName} (${dev.emailId})`);
      } else {
        console.log(`- Developer already exists: ${dev.emailId}`);
      }
    }

    console.log("Seeding completed successfully! Default password for all dummy users: 'Password@123'");
    process.exit(0);
  } catch (err) {
    console.error("Seeding error:", err);
    process.exit(1);
  }
}

seed();
